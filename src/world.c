static uint8_t scarecrow_world_current_chunk_x = 0;
static uint8_t scarecrow_world_current_chunk_y = 0;

uint8_t scarecrow_world_get_current_chunk_x(void)
{
    return scarecrow_world_current_chunk_x;
}

uint8_t scarecrow_world_get_current_chunk_y(void)
{
    return scarecrow_world_current_chunk_y;
}

void scarecrow_world_set_current_chunk_x(const uint8_t value)
{
    scarecrow_world_current_chunk_x = value;
}

void scarecrow_world_set_current_chunk_y(const uint8_t value)
{
    scarecrow_world_current_chunk_y = value;
}

void scarecrow_world_load_chunk(void)
{
    const scarecrow_world_chunk *chunk = &scarecrow_world_chunks[scarecrow_mathematics_flatten_2d_index(scarecrow_world_current_chunk_x, scarecrow_world_current_chunk_y, SCARECROW_CONSTANTS_WORLD_WIDTH)];

    for (uint8_t y = 0; y < SCARECROW_CONSTANTS_WORLD_CHUNK_HEIGHT; ++y)
    {
        for (uint8_t x = 0; x < SCARECROW_CONSTANTS_WORLD_CHUNK_WIDTH; ++x)
        {
            scarecrow_tilemap_set_tile_type(x, y, chunk->tiles[scarecrow_mathematics_flatten_2d_index(x, y, SCARECROW_CONSTANTS_WORLD_CHUNK_WIDTH)]);
        }
    }
}
